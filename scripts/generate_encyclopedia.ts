function generatePlants(): Plant[] {
  const plants: Plant[] = [];
  let count = 0;
  const rankDist = [
    { level: 1, subranks: ["1.1", "1.2", "1.3", "1.4", "1.5"], count: 80 },
    { level: 2, subranks: ["2.1", "2.2", "2.3", "2.4", "2.5"], count: 80 },
    { level: 3, subranks: ["3.1", "3.2", "3.3", "3.4", "3.5"], count: 70 },
    { level: 4, subranks: ["4.1", "4.2", "4.3", "4.4", "4.5"], count: 45 },
    { level: 5, subranks: ["5.1", "5.2", "5.3", "5.4", "5.5"], count: 25 }
  ];

  for (const group of rankDist) {
    for (let i = 0; i < group.count; i++) {
      count++;
      const subrank = group.subranks[i % group.subranks.length];
      const adj = plantAdjectives[(count * 7 + i * 3) % plantAdjectives.length];
      const root = plantRoots[(count * 11 + i * 5) % plantRoots.length];
      const category = plantCategories[(count + i * 2) % plantCategories.length];
      const element = plantElements[(count * 3 + i) % plantElements.length];
      const region = regions[(count * 4 + i) % regions.length];

      let name = `${adj} ${root}`;
      if (group.level === 5) {
        name = `Великое ${root}-Древо ${adj}`;
      } else if (group.level === 4) {
        name = `Древний ${adj} ${root}`;
      }

      plants.push({
        id: count,
        name,
        rank: subrank,
        rankLevel: group.level,
        category,
        element,
        region,
        description: `Характерное для региона ${region} растение с выраженным резонансом стихии ${element}. Волокна содержат микроканалы Истока плотностью уровня ${subrank}.`,
        harvest: `Сбор побегов, сердцевины, эфирного сока или коры в сезон ${subrank === "1.1" ? "Цветель" : "Зрельник"}.`,
        usage: `Применяется в производстве: ${category === "Алхимическое" ? "эликсиров стабилизации Ядра и мазей от выгорания" : category === "Проводник Истока" ? "рукоятей рунного оружия и ламинации луков" : category === "Токсичное/Боевое" ? "парализующих вытяжек для стрел и ловушек" : category === "Конструкционное" ? "укрепления фортификаций и обшивки судов" : "питательных рационов для культиваторов"}.`,
        connections: `Используется фракцией ${count % 3 === 0 ? "[[Фракции - Кланы Двуречья|Кланы Двуречья]]" : count % 3 === 1 ? "[[Фракции - Морской Союз|Морской Союз]]" : "[[Фракции - Орда Трёх Костров|Орда Трёх Костров]]"}, связь с дисциплиной [[Выгорание|регенерации каналов]].`
      });
    }
  }
  return plants;
}

